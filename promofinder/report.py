"""Write every output an editor (or a reviewer) needs, all from one run."""
from __future__ import annotations

import csv
import html
import json
import os

from .parse import fmt


def promo_dict(c):
    d = c.desc
    return {
        "rank": c.rank, "id": c.pid, "type": c.kind, "episodes": c.episodes,
        "segments": [s.to_dict() for s in c.segments], "total_duration_sec": c.duration,
        "hook": d["hook"], "hook_at_sec": d["hook_at_sec"], "cliffhanger": d["cliffhanger"],
        "why_it_works": d["why"], "why_post_here": c.post_reason,
        "post_score": c.post_score, "rules_score": c.score, "score_parts": c.parts,
        "qa": c.qa, "flags": c.flags,
        "llm": getattr(c, "llm", None),
        "rules_text": {k: d[k] for k in ("hook_rules", "cliffhanger_rules", "why_rules") if k in d},
        "transcript": d["transcript"],
    }


def write_all(res, out_dir, run_info, log_lines, eval_result=None, top=15):
    os.makedirs(out_dir, exist_ok=True)
    promos = res["promos"]
    rows = [promo_dict(c) for c in promos]

    with open(os.path.join(out_dir, "promos.json"), "w", encoding="utf-8") as f:
        json.dump({"show": res["title"], "episodes": res["episodes"], "run": run_info,
                   "premise_terms": res["premise_terms"], "promos": rows}, f, ensure_ascii=False, indent=1)

    with open(os.path.join(out_dir, "promos.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["rank", "id", "type", "episodes", "cuts (episode start-end, in order)", "total_sec",
                    "hook", "cliffhanger", "why_it_works", "why_post_here", "post_score", "qa_pass",
                    "qa_issues", "flags"])
        for r, c in zip(rows, promos):
            w.writerow([r["rank"], r["id"], r["type"], " + ".join(map(str, r["episodes"])),
                        " | ".join(c.desc["cuts"]), r["total_duration_sec"], r["hook"], r["cliffhanger"],
                        r["why_it_works"], r["why_post_here"], r["post_score"], r["qa"]["pass"],
                        "; ".join(r["qa"]["issues"] + r["qa"]["warnings"]), ";".join(r["flags"])])

    with open(os.path.join(out_dir, "edit_decision_list.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["promo_id", "rank", "cut_order", "episode", "source_file", "start", "end", "duration_sec"])
        for c in promos:
            for k, s in enumerate(c.segments, 1):
                w.writerow([c.pid, c.rank, k, s.episode, os.path.basename(res["index"][s.episode].ep.path),
                            fmt(s.start), fmt(s.end), s.dur])

    with open(os.path.join(out_dir, "shortlist.md"), "w", encoding="utf-8") as f:
        f.write(f"# Post-first shortlist: {res['title']}\n\n")
        f.write(f"Generated by promo-finder ({run_info['mode']}). Top {top} of {len(promos)} promos, "
                f"in the order we would post them. Every timestamp is copied from the screenplay.\n\n")
        for c, r in zip(promos[:top], rows[:top]):
            f.write(f"## {c.rank}. {c.pid} - {c.kind.replace('_', ' ')}, {c.duration:.0f}s\n\n")
            f.write("**Cuts:** " + " -> ".join(c.desc["cuts"]) + "\n\n")
            f.write(f"- **Hook ({r['hook_at_sec']:.1f}s in):** {r['hook']}\n")
            f.write(f"- **Cliffhanger:** {r['cliffhanger']}\n")
            f.write(f"- **Why it works:** {r['why_it_works']}\n")
            f.write(f"- **Why post it here:** {r['why_post_here']}\n")
            qa = "pass" if r["qa"]["pass"] else "FAIL: " + "; ".join(r["qa"]["issues"])
            if r["qa"]["warnings"]:
                qa += " | " + "; ".join(r["qa"]["warnings"])
            f.write(f"- **Auto-QA:** {qa}\n\n")
            f.write("<details><summary>Transcript</summary>\n\n")
            for t in r["transcript"]:
                f.write(f"- `{t['t']:5.1f}s` (cut {t['seg']}) {t['line']}\n")
            f.write("\n</details>\n\n")

    _write_html(res, rows, os.path.join(out_dir, "report.html"), run_info)
    _write_qa(res, rows, os.path.join(out_dir, "qa_report.md"), eval_result)
    with open(os.path.join(out_dir, "run_log.txt"), "w", encoding="utf-8") as f:
        f.write(json.dumps(run_info, indent=1) + "\n\n" + "\n".join(log_lines) + "\n")
        if res.get("judge_log"):
            f.write("\n[llm judge notes]\n")
            for n in res["judge_log"]:
                f.write(json.dumps(n, ensure_ascii=False) + "\n")


def _write_qa(res, rows, path, ev):
    n = len(rows)
    passed = sum(r["qa"]["pass"] for r in rows)
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"# Quality report: {res['title']}\n\n")
        f.write("## Automatic checks (every promo)\n\n")
        f.write(f"{passed}/{n} promos pass every hard check: 20-60 s total, hook beat in the first 3 s, "
                "no dialogue line clipped at any cut, segments in order and in bounds, no dead air at the open, "
                "ending not a resolution, not opening mid-sentence, no sub-2.5 s jump cuts.\n\n")
        fails = [r for r in rows if not r["qa"]["pass"]]
        if fails:
            f.write("| rank | id | issue |\n|---|---|---|\n")
            for r in fails:
                f.write(f"| {r['rank']} | {r['id']} | {'; '.join(r['qa']['issues'])} |\n")
        warn = [r for r in rows if r["qa"]["warnings"]]
        f.write(f"\n{len(warn)} promos carry an ad-policy warning (flagged for human review, ranked lower, "
                "not removed):\n\n")
        for r in warn:
            f.write(f"- {r['rank']}. {r['id']} ({', '.join('Ep%s' % e for e in r['episodes'])}): "
                    f"{'; '.join(r['qa']['warnings'])}\n")
        if ev:
            f.write("\n## Against hand-labelled editor picks\n\n")
            f.write(f"Gold set: {ev['n_gold']} moments I marked while reading all 50 episodes, "
                    f"{ev['n_gold_A']} of them tier A (\"would post this week\"). Frozen before tuning.\n\n")
            f.write("| metric | value |\n|---|---|\n")
            for k in ("recall_all", "recall_A_all", "recall@10", "recall_A@10", "precision@10",
                      "recall@15", "recall_A@15", "precision@15", "recall@30", "recall_A@30", "precision@30"):
                f.write(f"| {k} | {ev[k]:.0%} |\n")
            f.write("\nPrecision counts a pick as right only if it overlaps a gold moment, so it is a lower bound "
                    "(the gold list is not exhaustive).\n\n")
            if ev.get("split"):
                f.write("| slice | gold | found | recall | tier-A found |\n|---|---|---|---|---|\n")
                for k, v in ev["split"].items():
                    f.write(f"| {k} | {v['gold']} | {v['found']} | {v['recall']:.0%} | "
                            f"{v['found_A']}/{v['gold_A']} |\n")
            f.write("\n### Gold moments and the best rank at which the tool surfaced them\n\n")
            f.write("| id | tier | ep | moment | best rank |\n|---|---|---|---|---|\n")
            for g in ev["gold_rows"]:
                rk = ev["found_by_rank"][g["id"]]
                f.write(f"| {g['id']} | {g['tier']} | {g['episode']} | {g['label']} | "
                        f"{rk if rk else '**missed**'} |\n")
            if ev.get("unmatched_top"):
                f.write("\n### Top-30 picks that match no gold moment (manual review)\n\n")
                for r in ev["unmatched_top"]:
                    f.write(f"- {r}\n")


def _esc(s):
    return html.escape(str(s))


def _write_html(res, rows, path, run_info):
    cards = []
    for r in rows:
        segs = "".join(f"<span class='seg'>Ep {s['episode']} &middot; {s['start']}&ndash;{s['end']} "
                       f"<small>({s['duration']:.1f}s)</small></span>" for s in r["segments"])
        tr = "".join(f"<li><code>{t['t']:5.1f}s</code> {_esc(t['line'])}</li>" for t in r["transcript"])
        qa = ("<span class='ok'>QA pass</span>" if r["qa"]["pass"]
              else "<span class='bad'>QA: " + _esc("; ".join(r["qa"]["issues"])) + "</span>")
        warn = "".join(f"<span class='warn'>{_esc(w)}</span>" for w in r["qa"]["warnings"])
        cards.append(f"""
<article data-type="{r['type']}" data-pass="{int(r['qa']['pass'])}">
  <header><b>#{r['rank']}</b> <span class="pill">{_esc(r['type'].replace('_', ' '))}</span>
  <span class="dur">{r['total_duration_sec']:.0f}s</span> {qa} {warn}</header>
  <div class="segs">{segs}</div>
  <p><b>Hook</b> <small>({r['hook_at_sec']:.1f}s in)</small>: {_esc(r['hook'])}</p>
  <p><b>Cliffhanger</b>: {_esc(r['cliffhanger'])}</p>
  <p><b>Why it works</b>: {_esc(r['why_it_works'])}</p>
  <p class="muted"><b>Why post it here</b>: {_esc(r['why_post_here'])}</p>
  <details><summary>Transcript ({len(r['transcript'])} beats)</summary><ol>{tr}</ol></details>
</article>""")
    doc = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>Promo picks</title>
<style>
:root{{--bg:#faf9f7;--fg:#1d1b19;--muted:#6b655e;--card:#fff;--line:#e6e1da;--accent:#b4462b;--ok:#2f7a4a;--bad:#b42b2b;--warn:#8a6a10}}
@media (prefers-color-scheme: dark){{:root{{--bg:#151413;--fg:#ece8e3;--muted:#a39b92;--card:#1f1d1b;--line:#34302c;--accent:#e2795d;--ok:#6cc08b;--bad:#ef7b7b;--warn:#e0c060}}}}
body{{background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,-apple-system,Segoe UI,sans-serif;margin:0;padding:24px 16px}}
main{{max-width:880px;margin:auto}} h1{{font-size:22px;margin:0 0 4px}} .muted,small{{color:var(--muted)}}
.bar{{display:flex;gap:8px;flex-wrap:wrap;margin:16px 0}} button{{border:1px solid var(--line);background:var(--card);color:var(--fg);border-radius:6px;padding:6px 10px;cursor:pointer}}
button.on{{border-color:var(--accent);color:var(--accent)}}
article{{background:var(--card);border:1px solid var(--line);border-radius:10px;padding:14px 16px;margin:12px 0}}
article p{{margin:6px 0}} header{{display:flex;gap:8px;align-items:center;flex-wrap:wrap}}
.pill{{font-size:12px;border:1px solid var(--line);border-radius:99px;padding:1px 8px}} .dur{{font-weight:600}}
.segs{{display:flex;flex-wrap:wrap;gap:6px;margin:8px 0}} .seg{{font:13px ui-monospace,Menlo,monospace;background:var(--bg);border:1px solid var(--line);border-radius:6px;padding:2px 6px}}
.ok{{color:var(--ok);font-size:13px}} .bad{{color:var(--bad);font-size:13px}} .warn{{color:var(--warn);font-size:13px}}
ol{{padding-left:20px}} code{{color:var(--muted)}}
</style></head><body><main>
<h1>Promo picks: {_esc(res['title'])}</h1>
<div class="muted">{len(rows)} promos from {res['episodes']} episodes &middot; mode: {_esc(run_info['mode'])} &middot; ranked in posting order</div>
<div class="bar"><button class="on" data-f="all">All</button><button data-f="single">Single</button>
<button data-f="stitched">Stitched</button><button data-f="cross_episode">Cross-episode</button>
<button data-f="montage">Trailers</button><button data-f="fail">QA issues</button></div>
{''.join(cards)}
</main><script>
document.querySelectorAll('.bar button').forEach(b=>b.onclick=()=>{{
 document.querySelectorAll('.bar button').forEach(x=>x.classList.remove('on'));b.classList.add('on');
 const f=b.dataset.f;document.querySelectorAll('article').forEach(a=>{{
  a.style.display=(f==='all'||a.dataset.type===f||(f==='fail'&&a.dataset.pass==='0'))?'':'none'}})}});
</script></body></html>"""
    with open(path, "w", encoding="utf-8") as f:
        f.write(doc)
